package main

import (
	"fmt"
	"go/format"
	"net/http"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"
)

type catalogue struct {
	Codes []codeEntry `yaml:"codes"`
}

type codeEntry struct {
	Code      string `yaml:"code"`
	Status    int    `yaml:"status"`
	Title     string `yaml:"title"`
	Cause     string `yaml:"cause"`
	Fix       string `yaml:"fix"`
	Retryable bool   `yaml:"retryable"`
	Billable  bool   `yaml:"billable"`
}

var codePattern = regexp.MustCompile(`^[A-Z]+-[0-9]+$`)

// goIdent turns "AUTH-4010" into "AUTH4010".
func goIdent(code string) string {
	return strings.ReplaceAll(code, "-", "")
}

const generatedTemplate = `// Code generated by tools/errcodes from docs/errors/catalogue.yaml. DO NOT EDIT.

package problem

// Code identifies a VASPRO error, in the form FAMILY-NNNN (system design §8).
type Code string

// entry is the catalogue data behind a Code: everything New needs to build
// a Problem, and nothing a caller should read directly.
type entry struct {
	Status    int
	Title     string
	Cause     string
	Fix       string
	Retryable bool
	Billable  bool
}

const (
{{- range .Codes}}
	{{.Ident}} Code = {{.CodeQuoted}}
{{- end}}
)

var registry = map[Code]entry{
{{- range .Codes}}
	{{.Ident}}: {
		Status:    {{.Status}},
		Title:     {{.TitleQuoted}},
		Cause:     {{.CauseQuoted}},
		Fix:       {{.FixQuoted}},
		Retryable: {{.Retryable}},
		Billable:  {{.Billable}},
	},
{{- end}}
}
`

type templateCode struct {
	Ident       string
	CodeQuoted  string
	TitleQuoted string
	CauseQuoted string
	FixQuoted   string
	codeEntry
}

// Generate reads a docs/errors/catalogue.yaml-shaped YAML document and
// returns the Go source for internal/platform/problem/codes_gen.go.
func Generate(data []byte) ([]byte, error) {
	var cat catalogue
	if err := yaml.Unmarshal(data, &cat); err != nil {
		return nil, fmt.Errorf("errcodes: parsing catalogue: %w", err)
	}

	seen := make(map[string]bool, len(cat.Codes))
	codes := make([]templateCode, 0, len(cat.Codes))
	for _, c := range cat.Codes {
		if !codePattern.MatchString(c.Code) {
			return nil, fmt.Errorf("errcodes: %q is not a valid code (want FAMILY-NNNN)", c.Code)
		}
		if seen[c.Code] {
			return nil, fmt.Errorf("errcodes: duplicate code %q", c.Code)
		}
		seen[c.Code] = true

		if http.StatusText(c.Status) == "" {
			return nil, fmt.Errorf("errcodes: %q has an invalid HTTP status %d", c.Code, c.Status)
		}

		codes = append(codes, templateCode{
			Ident:       goIdent(c.Code),
			CodeQuoted:  strconv.Quote(c.Code),
			TitleQuoted: strconv.Quote(c.Title),
			CauseQuoted: strconv.Quote(c.Cause),
			FixQuoted:   strconv.Quote(c.Fix),
			codeEntry:   c,
		})
	}

	sort.Slice(codes, func(i, j int) bool { return codes[i].Code < codes[j].Code })

	tmpl, err := template.New("codes_gen").Parse(generatedTemplate)
	if err != nil {
		return nil, fmt.Errorf("errcodes: parsing template: %w", err)
	}

	var buf strings.Builder
	if err := tmpl.Execute(&buf, struct{ Codes []templateCode }{codes}); err != nil {
		return nil, fmt.Errorf("errcodes: rendering template: %w", err)
	}

	formatted, err := format.Source([]byte(buf.String()))
	if err != nil {
		return nil, fmt.Errorf("errcodes: formatting generated source: %w", err)
	}
	return formatted, nil
}
