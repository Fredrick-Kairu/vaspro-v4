func (d doc) renderErrors(b *bytes.Buffer, op operation, desc string, codes map[string]codeEntry) {
	var list []string
	seen := map[string]bool{}
	add := func(c string) {
		if _, ok := codes[c]; ok && !seen[c] {
			seen[c] = true
			list = append(list, c)
		}
	}
	for _, c := range codeMention.FindAllString(str(get(op.Node, "description")), -1) {
		add(c)
	}
	for _, c := range extraCodes[op.ID] {
		add(c)
	}
	if strings.Contains(desc, "AUTH-4023") {
		add("AUTH-4024")
	}
	sec := get(op.Node, "security")
	if sec != nil && len(sec.Content) > 0 {
		add("AUTH-4010")
	}
	if strings.Contains(op.Path, "/staff/") {
		add("AUTH-4025")
	}
	if strings.HasPrefix(op.Path, "/v1/accounts/tenants/{id}") {
		add("AUTH-4024")
		add("VAL-4003")
	}
	if strings.Contains(op.Path, "{") {
		add("VAL-4003")
	}
	if get(op.Node, "requestBody") != nil || get(op.Node, "parameters") != nil {
		add("VAL-4000")
	}
	if params := get(op.Node, "parameters"); params != nil {
		for _, p := range params.Content {
			if str(get(d.resolve(p), "name")) == "Idempotency-Key" {
				add("VAL-4001")
			}
		}
	}
	if len(list) == 0 {
		return
	}
	b.WriteString("**Errors**\n\n| Code | HTTP | Meaning | When |\n|---|---|---|---|\n")
	for _, c := range list {
		e := codes[c]
		fmt.Fprintf(b, "| `%s` | %d | %s | %s |\n", e.Code, e.Status, cell(e.Title), cell(e.Cause))
	}
	b.WriteString("\n")
}

func renderCatalogue(b *bytes.Buffer, codes []codeEntry) {
	b.WriteString("\n---\n\n## Error catalogue\n\nEvery code the platform defines. Codes from families that aren't live yet (messaging, routing, payments) are listed so clients can be ready for them.\n\n")
	b.WriteString("| Code | HTTP | Title | Cause | What to do |\n|---|---|---|---|---|\n")
	for _, c := range codes {
		fmt.Fprintf(b, "| `%s` | %d | %s | %s | %s |\n", c.Code, c.Status, cell(c.Title), cell(cleanDescription(c.Cause)), cell(cleanDescription(c.Fix)))
	}
}

// --- schemas ---------------------------------------------------------

type field struct {
	name     string
	schema   *yaml.Node
	required bool
}

// properties lists an object schema's properties in file order, merging
// allOf parts.
func (d doc) properties(schema *yaml.Node) []field {
	schema = d.resolve(schema)
	if schema == nil {
		return nil
	}
	var out []field
	if all := get(schema, "allOf"); all != nil {
		for _, part := range all.Content {
			out = append(out, d.properties(part)...)
		}
	}
	required := map[string]bool{}
	if r := get(schema, "required"); r != nil {
		for _, n := range r.Content {
			required[n.Value] = true
		}
	}
	if props := get(schema, "properties"); props != nil {
		for i := 0; i+1 < len(props.Content); i += 2 {
			out = append(out, field{name: props.Content[i].Value, schema: props.Content[i+1], required: required[props.Content[i].Value]})
		}
	}
	return out
}

func (d doc) renderFields(b *bytes.Buffer, schema *yaml.Node) {
	var rows []string
	d.fieldRows(&rows, schema, "", 0)
	if len(rows) == 0 {
		return
	}
	b.WriteString("| Field | Type | Required | Description |\n|---|---|---|---|\n")
	for _, r := range rows {
		b.WriteString(r + "\n")
	}
	b.WriteString("\n")
}

func (d doc) fieldRows(rows *[]string, schema *yaml.Node, prefix string, depth int) {
	if depth > 4 {
		return
	}
	for _, f := range d.properties(schema) {
		s := d.resolve(f.schema)
		name := prefix + f.name
		*rows = append(*rows, fmt.Sprintf("| `%s` | %s | %s | %s |", name, d.typeOf(f.schema), yesNo(f.required), cell(cleanDescription(str(get(s, "description"))))))
		switch str(get(s, "type")) {
		case "array":
			d.fieldRows(rows, get(s, "items"), name+"[].", depth+1)
		default:
			d.fieldRows(rows, s, name+".", depth+1)
		}
	}
}

func (d doc) typeOf(schema *yaml.Node) string {
	s := d.resolve(schema)
	if s == nil {
		return ""
	}
	if get(s, "allOf") != nil {
		return "object"
	}
	t := str(get(s, "type"))
	if t == "" && get(s, "type") != nil && get(s, "type").Kind == yaml.SequenceNode {
		var ts []string
		for _, n := range get(s, "type").Content {
			ts = append(ts, n.Value)
		}
		t = strings.Join(ts, " \\| ")
	}
	if t == "array" {
		return "array of " + d.typeOf(get(s, "items"))
	}
	if f := str(get(s, "format")); f != "" {
		t += " (" + f + ")"
	}
	if e := get(s, "enum"); e != nil {
		var vs []string
		for _, n := range e.Content {
			vs = append(vs, "`"+n.Value+"`")
		}
		t += ": " + strings.Join(vs, ", ")
	}
	if t == "" {
		t = "any"
	}
	return t
}

// sample builds an example value from a schema, using its example,
// default or enum where it has one, and the field's name otherwise.
func (d doc) sample(schema *yaml.Node, name string, depth int) any {
	s := d.resolve(schema)
	if s == nil || depth > 6 {
		return nil
	}
	if ex := get(s, "example"); ex != nil {
		return fromNode(ex)
	}
	if def := get(s, "default"); def != nil {
		return fromNode(def)
	}
	if e := get(s, "enum"); e != nil && len(e.Content) > 0 {
		return fromNode(e.Content[0])
	}
	if get(s, "allOf") != nil || get(s, "properties") != nil {
		o := &object{}
		for _, f := range d.properties(s) {
			o.add(f.name, d.sample(f.schema, f.name, depth+1))
		}
		return o
	}
	switch str(get(s, "type")) {
	case "array":
		item := d.sample(get(s, "items"), strings.TrimSuffix(name, "s"), depth+1)
		if item == nil {
			return []any{}
		}
		return []any{item}
	case "object":
		return &object{}
	case "integer":
		return 1
	case "number":
		return 1
	case "boolean":
		return true
	}
	return sampleString(name, str(get(s, "format")))
}

