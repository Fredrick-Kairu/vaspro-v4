//go:embed intro.md
var intro string

type specFile struct {
	Path  string
	Title string
}

type loadedSpec struct {
	specFile
	Data []byte
}

type codeEntry struct {
	Code   string `yaml:"code"`
	Status int    `yaml:"status"`
	Title  string `yaml:"title"`
	Cause  string `yaml:"cause"`
	Fix    string `yaml:"fix"`
}

// doc is one parsed spec. yaml.Node keeps the file's order of paths,
// methods and properties, which a decoded map would lose.
type doc struct {
	root *yaml.Node
}

type operation struct {
	Method string
	Path   string
	Node   *yaml.Node
	ID     string
	Group  string
}

var methods = []string{"get", "post", "put", "patch", "delete"}

// Generate renders the reference from the specs and the catalogue.
func Generate(specs []loadedSpec, catalogue []byte) ([]byte, error) {
	var cat struct {
		Codes []codeEntry `yaml:"codes"`
	}
	if err := yaml.Unmarshal(catalogue, &cat); err != nil {
		return nil, fmt.Errorf("apidocs: parsing the catalogue: %w", err)
	}
	codes := make(map[string]codeEntry, len(cat.Codes))
	for _, c := range cat.Codes {
		codes[c.Code] = c
	}

	type parsed struct {
		spec loadedSpec
		doc  doc
		ops  []operation
	}
	all := make([]parsed, 0, len(specs))
	for _, s := range specs {
		var root yaml.Node
		if err := yaml.Unmarshal(s.Data, &root); err != nil {
			return nil, fmt.Errorf("apidocs: parsing %s: %w", s.Path, err)
		}
		d := doc{root: root.Content[0]}
		ops, err := d.operations()
		if err != nil {
			return nil, fmt.Errorf("apidocs: %s: %w", s.Path, err)
		}
		all = append(all, parsed{spec: s, doc: d, ops: ops})
	}

	var b bytes.Buffer
	b.WriteString("<!-- Generated by tools/apidocs from docs/api/*.yaml, docs/errors/catalogue.yaml and tools/apidocs/intro.md. DO NOT EDIT; run `make gen`. -->\n\n")
	b.WriteString(strings.TrimSpace(intro))
	b.WriteString("\n\n## Endpoint index\n\n")
	for _, p := range all {
		fmt.Fprintf(&b, "**%s**\n\n", p.spec.Title)
		group := ""
		for _, op := range p.ops {
			if op.Group != group {
				group = op.Group
				fmt.Fprintf(&b, "\n*%s*\n\n", group)
			}
			fmt.Fprintf(&b, "- [`%s %s`](#%s) %s\n", strings.ToUpper(op.Method), op.Path, anchor(op.ID), str(get(op.Node, "summary")))
		}
		b.WriteString("\n")
	}

	for _, p := range all {
		fmt.Fprintf(&b, "\n---\n\n## %s\n", p.spec.Title)
		group := ""
		for _, op := range p.ops {
			if op.Group != group {
				group = op.Group
				fmt.Fprintf(&b, "\n### %s\n", group)
			}
			p.doc.renderOperation(&b, op, codes)
		}
	}

	renderCatalogue(&b, cat.Codes)
	return b.Bytes(), nil
}

func anchor(id string) string { return "op-" + strings.ToLower(id) }

func (d doc) operations() ([]operation, error) {
	paths := get(d.root, "paths")
	if paths == nil {
		return nil, fmt.Errorf("no paths")
	}
	var ops []operation
	for i := 0; i+1 < len(paths.Content); i += 2 {
		path := paths.Content[i].Value
		item := paths.Content[i+1]
		for _, m := range methods {
			n := get(item, m)
			if n == nil {
				continue
			}
			id := str(get(n, "operationId"))
			if id == "" {
				return nil, fmt.Errorf("%s %s has no operationId", m, path)
			}
			ops = append(ops, operation{Method: m, Path: path, Node: n, ID: id, Group: groupOf(path)})
		}
	}
	// Keep each group together, in the order groups first appear.
	first := map[string]int{}
	for i, op := range ops {
		if _, ok := first[op.Group]; !ok {
			first[op.Group] = i
		}
	}
	sort.SliceStable(ops, func(i, j int) bool { return first[ops[i].Group] < first[ops[j].Group] })
	return ops, nil
}

