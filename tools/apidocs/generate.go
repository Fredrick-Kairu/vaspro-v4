func (d doc) renderOperation(b *bytes.Buffer, op operation, codes map[string]codeEntry) {
	n := op.Node
	fmt.Fprintf(b, "\n<a id=\"%s\"></a>\n#### %s\n\n", anchor(op.ID), str(get(n, "summary")))
	fmt.Fprintf(b, "```\n%s %s\n```\n\n", strings.ToUpper(op.Method), op.Path)

	desc := cleanDescription(str(get(n, "description")))
	fmt.Fprintf(b, "**Auth:** %s  \n**Operation ID:** `%s`\n\n", authLabel(op, str(get(n, "description"))), op.ID)
	if desc != "" {
		b.WriteString(desc + "\n\n")
	}

	d.renderParameters(b, n)
	d.renderRequestBody(b, n)
	d.renderResponses(b, n)
	d.renderErrors(b, op, desc, codes)
}

func authLabel(op operation, desc string) string {
	sec := get(op.Node, "security")
	session := sec != nil && len(sec.Content) > 0
	var parts []string
	switch {
	case session:
		parts = append(parts, "session token (`Authorization: Bearer <session_token>`)")
	case op.Path == "/v1/oauth/token":
		parts = append(parts, "API client credentials in the form body")
	default:
		parts = append(parts, "none")
	}
	if strings.Contains(desc, "AUTH-4012") {
		parts = append(parts, "a fresh step-up")
	}
	if strings.Contains(op.Path, "/staff/") || strings.Contains(desc, "AUTH-4025") {
		parts = append(parts, "VASPRO staff only")
	}
	if strings.Contains(desc, "AUTH-4023") {
		parts = append(parts, "a selected account on the session")
	}
	return strings.Join(parts, " + ")
}

var (
	// Parentheticals that point at internal planning documents.
	internalParen = regexp.MustCompile(`\s*\((?:[^()]*?(?:\btasks?\b|§|OQ-\d|ADR|\bD-\d|decision|roadmap|\.claude|carried from|data model|system design|identity's own)[^()]*)\)`)
	// Sentences that only make sense inside the repository.
	internalSentence = regexp.MustCompile(`(?i)\b(tasks? \d|§|OQ-\d|ADR \d|\.claude/|roadmap|data model|system design)`)
	sentenceEnd      = regexp.MustCompile(`([.!?])\s+`)
)

// cleanDescription drops references to the repository's planning
// documents, which mean nothing to an API consumer.
func cleanDescription(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	s = internalParen.ReplaceAllString(s, "")
	parts := sentenceEnd.Split(s, -1)
	ends := sentenceEnd.FindAllStringSubmatch(s, -1)
	var kept []string
	for i, p := range parts {
		sentence := p
		if i < len(ends) {
			sentence += ends[i][1]
		}
		if strings.TrimSpace(sentence) == "" || internalSentence.MatchString(sentence) {
			continue
		}
		kept = append(kept, sentence)
	}
	return strings.TrimSpace(strings.Join(kept, " "))
}

func (d doc) renderParameters(b *bytes.Buffer, n *yaml.Node) {
	params := get(n, "parameters")
	if params == nil || len(params.Content) == 0 {
		return
	}
	b.WriteString("**Parameters**\n\n| Name | In | Required | Type | Description |\n|---|---|---|---|---|\n")
	for _, p := range params.Content {
		p = d.resolve(p)
		desc := cleanDescription(str(get(p, "description")))
		if str(get(p, "name")) == "Idempotency-Key" {
			desc = "A fresh unique value (e.g. a UUID) per action; reuse it only to retry the same request."
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n",
			str(get(p, "name")), str(get(p, "in")), yesNo(str(get(p, "required")) == "true"),
			d.typeOf(get(p, "schema")), cell(desc))
	}
	b.WriteString("\n")
}

func (d doc) renderRequestBody(b *bytes.Buffer, n *yaml.Node) {
	body := get(n, "requestBody")
	if body == nil {
		return
	}
	body = d.resolve(body)
	content := get(body, "content")
	if content == nil || len(content.Content) < 2 {
		return
	}
	ctype, media := content.Content[0].Value, content.Content[1]
	schema := get(media, "schema")
	fmt.Fprintf(b, "**Request body** (`%s`)\n\n", ctype)
	d.renderFields(b, schema)

	switch ctype {
	case "application/json":
		var sample any
		if ex := get(media, "example"); ex != nil {
			sample = fromNode(ex)
		} else {
			sample = d.sample(schema, "", 0)
		}
		b.WriteString("Example:\n\n```json\n" + encodeJSON(sample, "") + "\n```\n\n")
	case "application/x-www-form-urlencoded":
		var pairs []string
		for _, f := range d.properties(schema) {
			pairs = append(pairs, f.name+"="+fmt.Sprint(d.sample(f.schema, f.name, 1)))
		}
		b.WriteString("Example:\n\n```\n" + strings.Join(pairs, "&") + "\n```\n\n")
	case "multipart/form-data":
		b.WriteString("Example (curl):\n\n```\n")
		var parts []string
		for _, f := range d.properties(schema) {
			if str(get(d.resolve(f.schema), "format")) == "binary" {
				parts = append(parts, fmt.Sprintf("-F '%s=@certificate.pdf'", f.name))
			} else {
				parts = append(parts, fmt.Sprintf("-F '%s=%v'", f.name, d.sample(f.schema, f.name, 1)))
			}
		}
		b.WriteString(strings.Join(parts, " \\\n") + "\n```\n\n")
	}
}

func (d doc) renderResponses(b *bytes.Buffer, n *yaml.Node) {
	resp := get(n, "responses")
	if resp == nil {
		return
	}
	for i := 0; i+1 < len(resp.Content); i += 2 {
		status := resp.Content[i].Value
		if !strings.HasPrefix(status, "2") && !strings.HasPrefix(status, "3") {
			continue
		}
		r := d.resolve(resp.Content[i+1])
		fmt.Fprintf(b, "**Response `%s`**: %s\n\n", status, cleanDescription(str(get(r, "description"))))
		content := get(r, "content")
		if content == nil || len(content.Content) < 2 {
			continue
		}
		ctype, media := content.Content[0].Value, content.Content[1]
		schema := get(media, "schema")
		if ctype != "application/json" {
			fmt.Fprintf(b, "Body: the raw file (`%s`).\n\n", ctype)
			continue
		}
		d.renderFields(b, schema)
		var sample any
		if ex := get(media, "example"); ex != nil {
			sample = fromNode(ex)
		} else {
			sample = d.sample(schema, "", 0)
		}
		b.WriteString("```json\n" + encodeJSON(sample, "") + "\n```\n\n")
	}
}

