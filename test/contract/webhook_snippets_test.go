var updateVectors = flag.Bool("update", false, "rewrite docs/webhooks/verify/testdata/vectors.json from our signer")

const (
	snippetsDir = "../../docs/webhooks/verify"
	vectorsPath = snippetsDir + "/testdata/vectors.json"
)

// The secrets signature_test.go uses: the bytes 0..31, 32..63 and 64..95
// in base64url, made up and never used anywhere real.
const (
	vecSecretA = "whsec_AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8" //nolint:gosec // G101: a made-up test secret (bytes 0..31). gitleaks:allow
	vecSecretB = "whsec_ICEiIyQlJicoKSorLC0uLzAxMjM0NTY3ODk6Ozw9Pj8" //nolint:gosec // G101: a made-up test secret (bytes 32..63). gitleaks:allow
	vecSecretC = "whsec_QEFCQ0RFRkdISUpLTE1OT1BRUlNUVVZXWFlaW1xdXl8" //nolint:gosec // G101: a made-up test secret (bytes 64..95). gitleaks:allow
)

// The outcomes a snippet reports.
const (
	outcomeOK           = "ok"
	outcomeBadTimestamp = "bad_timestamp"
	outcomeBadSignature = "bad_signature"
)

// vector is one case the snippets check: verify(secret, timestamp,
// signature, body) at now must give expect.
type vector struct {
	Name       string `json:"name"`
	Secret     string `json:"secret"`
	Now        int64  `json:"now"`
	Timestamp  string `json:"timestamp"`
	Signature  string `json:"signature"`
	BodyBase64 string `json:"body_base64"`
	Expect     string `json:"expect"`
}

type vectorFile struct {
	Comment string   `json:"comment"`
	Vectors []vector `json:"vectors"`
}

// TestWebhookVectors_MatchOurSigner builds the golden vectors from our
// signer, checks our own Verify gives each case's declared outcome, and
// requires the committed file to be exactly that. -update rewrites it.
func TestWebhookVectors_MatchOurSigner(t *testing.T) {
	vs := buildVectors(t)
	for _, v := range vs {
		body, _ := base64.StdEncoding.DecodeString(v.BodyBase64)
		err := domain.Verify(v.Secret, v.Timestamp, v.Signature, body, time.Unix(v.Now, 0))
		if got := outcomeOf(err); got != v.Expect {
			t.Errorf("%s: our Verify gives %s (%v), the case declares %s", v.Name, got, err, v.Expect)
		}
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(vectorFile{
		Comment: "Generated by test/contract/webhook_snippets_test.go from VASPRO's signer (go test -tags=contract -update). Made-up secrets; do not edit by hand.",
		Vectors: vs,
	}); err != nil {
		t.Fatal(err)
	}

	if *updateVectors {
		if err := os.WriteFile(vectorsPath, buf.Bytes(), 0o644); err != nil { //nolint:gosec // non-sensitive test vectors
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("reading %s (run with -update to create it): %v", vectorsPath, err)
	}
	if !bytes.Equal(committed, buf.Bytes()) {
		t.Fatalf("%s differs from what our signer produces; run with -update and review the diff", vectorsPath)
	}
}

// TestWebhookSnippets_VerifyOurVectors runs each language's snippet in
// its official image against the committed vectors.
func TestWebhookSnippets_VerifyOurVectors(t *testing.T) {
	raw, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	var vf vectorFile
	if err := json.Unmarshal(raw, &vf); err != nil {
		t.Fatal(err)
	}
	if len(vf.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	dir, err := filepath.Abs(snippetsDir)
	if err != nil {
		t.Fatal(err)
	}
	want := fmt.Sprintf("%d/%d vectors ok", len(vf.Vectors), len(vf.Vectors))

	for _, lang := range []struct {
		name, image, workdir string
		env                  map[string]string
		cmd                  []string
	}{
		{
			name: "go", image: "golang:1.26.11-alpine", workdir: "/verify/go",
			env: map[string]string{"GOTOOLCHAIN": "local", "GOPROXY": "off", "GOFLAGS": "-mod=mod"},
			cmd: []string{"sh", "-c", `out=$(gofmt -l .) && [ -z "$out" ] || { echo "gofmt: $out"; exit 1; }; go vet ./... && go run ./checkvectors /verify/testdata/vectors.json`},
		},
		{
			name: "php", image: "php:8.4.27-cli-alpine", workdir: "/verify/php",
			cmd: []string{"php", "check_vectors.php", "/verify/testdata/vectors.json"},
		},
		{
			name: "node", image: "node:22.23.5-alpine", workdir: "/verify/node",
			cmd: []string{"node", "check-vectors.js", "/verify/testdata/vectors.json"},
		},
		{
			name: "python", image: "python:3.13.18-alpine", workdir: "/verify/python",
			env: map[string]string{"PYTHONDONTWRITEBYTECODE": "1"},
			cmd: []string{"python", "check_vectors.py", "/verify/testdata/vectors.json"},
		},
	} {
		t.Run(lang.name, func(t *testing.T) {
			t.Parallel()
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
			defer cancel()

			ctr, err := testcontainers.Run(ctx, lang.image,
				testcontainers.WithFiles(testcontainers.ContainerFile{HostFilePath: dir, ContainerFilePath: "/verify", FileMode: 0o755}),
				testcontainers.WithEnv(lang.env),
				testcontainers.WithCmd(lang.cmd...),
				testcontainers.WithConfigModifier(func(c *container.Config) { c.WorkingDir = lang.workdir }),
				testcontainers.WithWaitStrategy(wait.ForExit().WithExitTimeout(4*time.Minute)),
			)
			testcontainers.CleanupContainer(t, ctr)
			if err != nil {
				t.Fatalf("running %s: %v", lang.image, err)
			}
			state, err := ctr.State(ctx)
			if err != nil {
				t.Fatal(err)
			}
			logs := containerLogs(ctx, t, ctr)
			if state.ExitCode != 0 {
				t.Fatalf("%s snippet exited %d:\n%s", lang.name, state.ExitCode, logs)
			}
			if !strings.Contains(logs, want) {
				t.Fatalf("%s snippet didn't report %q:\n%s", lang.name, want, logs)
			}
		})
	}
}

func containerLogs(ctx context.Context, t *testing.T, ctr testcontainers.Container) string {
	t.Helper()
	rc, err := ctr.Logs(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = rc.Close() }()
	b, err := io.ReadAll(rc)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func outcomeOf(err error) string {
	switch {
	case err == nil:
		return outcomeOK
	case errors.Is(err, domain.ErrBadTimestamp):
		return outcomeBadTimestamp
	case errors.Is(err, domain.ErrBadSignature):
		return outcomeBadSignature
	default:
		return "error: " + err.Error()
	}
}

// v1 is one signature value computed by hand, for a key or timestamp
// our signer would never use.
func v1(key []byte, timestamp string, body []byte) string {
	m := hmac.New(sha256.New, key)
	m.Write([]byte(timestamp + "."))
	m.Write(body)
	return "v1=" + hex.EncodeToString(m.Sum(nil))
}

func buildVectors(t *testing.T) []vector {
	t.Helper()
	at := time.Unix(1762941600, 0)
	now := at.Unix()
	ts := strconv.FormatInt(now, 10)
	body := []byte(`{"id":"evt_01JC0000000000000000000000","type":"wallet.credited","version":1,"tenant_id":"0193a000-0000-7000-8000-000000000001","occurred_at":"2025-11-12T10:00:00Z","data":{"amount_minor":500000,"currency":"KES"}}`)

	sign := func(secrets []string, b []byte) string {
		t.Helper()
		sig, err := domain.Sign(secrets, at, b)
		if err != nil {
			t.Fatal(err)
		}
		return sig.Value
	}
	one := sign([]string{vecSecretA}, body)
	rotation := sign([]string{vecSecretB, vecSecretA}, body)
	mk := func(name, secret string, now int64, timestamp, signature string, b []byte, expect string) vector {
		return vector{Name: name, Secret: secret, Now: now, Timestamp: timestamp, Signature: signature,
			BodyBase64: base64.StdEncoding.EncodeToString(b), Expect: expect}
	}

	flipped := bytes.Clone(body)
	flipped[10] ^= 0x01
	changedSecret := []byte(vecSecretA)
	changedSecret[20] = 'Z'
	changedHex := []byte(one)
	if changedHex[len(changedHex)-1] == '0' { // another hex digit, so only the value is wrong
		changedHex[len(changedHex)-1] = '1'
	} else {
		changedHex[len(changedHex)-1] = '0'
	}
	decoded, err := base64.RawURLEncoding.DecodeString(strings.TrimPrefix(vecSecretA, domain.SecretPrefix))
	if err != nil {
		t.Fatal(err)
	}
	nextTS := strconv.FormatInt(now+1, 10)
	unicodeBody := []byte(`{"id":"evt_2","type":"tenant.updated","data":{"display_name":"Wanjikũ Duka — Nairobi","note":"€ ✓ 日本"}}`)
	crlfBody := []byte("{\r\n  \"id\": \"evt_3\"\r\n}\r\n")

	vs := []vector{
		mk("one signature", vecSecretA, now, ts, one, body, outcomeOK),
		mk("rotation, the current secret", vecSecretB, now, ts, rotation, body, outcomeOK),
		mk("rotation, the previous secret", vecSecretA, now, ts, rotation, body, outcomeOK),
		mk("rotation, another secret", vecSecretC, now, ts, rotation, body, outcomeBadSignature),
		mk("rotation values separated by two spaces", vecSecretA, now, ts, strings.Replace(rotation, " ", "  ", 1), body, outcomeOK),
		mk("another secret", vecSecretC, now, ts, one, body, outcomeBadSignature),
		mk("one character of the secret changed", string(changedSecret), now, ts, one, body, outcomeBadSignature),
		mk("signed with the decoded secret bytes, not the whole string", vecSecretA, now, ts, v1(decoded, ts, body), body, outcomeBadSignature),
		mk("signed with the secret without its prefix", vecSecretA, now, ts, v1([]byte(strings.TrimPrefix(vecSecretA, domain.SecretPrefix)), ts, body), body, outcomeBadSignature),
		mk("one body byte changed", vecSecretA, now, ts, one, flipped, outcomeBadSignature),
		mk("body with a trailing newline", vecSecretA, now, ts, one, append(bytes.Clone(body), '\n'), outcomeBadSignature),
		mk("body re-serialised with spaces", vecSecretA, now, ts, one, bytes.ReplaceAll(body, []byte(`":`), []byte(`": `)), outcomeBadSignature),
		mk("a timestamp digit changed", vecSecretA, now+1, nextTS, one, body, outcomeBadSignature),
		mk("one hex digit of the signature changed", vecSecretA, now, ts, string(changedHex), body, outcomeBadSignature),
		mk("signature truncated", vecSecretA, now, ts, one[:len(one)-2], body, outcomeBadSignature),
		mk("upper-case hex", vecSecretA, now, ts, "v1="+strings.ToUpper(strings.TrimPrefix(one, "v1=")), body, outcomeOK),
		mk("an unknown scheme beside v1", vecSecretA, now, ts, "v0=deadbeef "+one+" v2=abc", body, outcomeOK),
		mk("an unknown scheme alone", vecSecretA, now, ts, "v2="+strings.TrimPrefix(one, "v1="), body, outcomeBadSignature),
		mk("malformed hex beside a good value", vecSecretA, now, ts, "v1=zz "+one, body, outcomeOK),
		mk("non-ASCII in the value", vecSecretA, now, ts, "v1=é"+strings.TrimPrefix(one, "v1=")[2:], body, outcomeBadSignature),
		mk("empty signature header", vecSecretA, now, ts, "", body, outcomeBadSignature),
		mk("v1= with nothing after it", vecSecretA, now, ts, "v1=", body, outcomeBadSignature),
		mk("exactly 5 minutes late", vecSecretA, now+300, ts, one, body, outcomeOK),
		mk("5 minutes and 1 second late", vecSecretA, now+301, ts, one, body, outcomeBadTimestamp),
		mk("exactly 5 minutes early", vecSecretA, now-300, ts, one, body, outcomeOK),
		mk("5 minutes and 1 second early", vecSecretA, now-301, ts, one, body, outcomeBadTimestamp),
		mk("a timestamp with a leading zero", vecSecretA, now, "0"+ts, v1([]byte(vecSecretA), "0"+ts, body), body, outcomeOK),
		mk("non-ASCII UTF-8 body", vecSecretA, now, ts, sign([]string{vecSecretA}, unicodeBody), unicodeBody, outcomeOK),
		mk("CRLF body", vecSecretA, now, ts, sign([]string{vecSecretA}, crlfBody), crlfBody, outcomeOK),
		mk("empty body", vecSecretA, now, ts, sign([]string{vecSecretA}, []byte{}), []byte{}, outcomeOK),
	}

	// Malformed timestamps, each signed as sent, so only the timestamp
	// rule can refuse it.
	for _, m := range []struct{ name, ts string }{
		{"empty timestamp", ""},
		{"timestamp in letters", "abc"},
		{"negative timestamp", "-" + ts},
		{"timestamp with a plus sign", "+" + ts},
		{"timestamp with a leading space", " " + ts},
		{"timestamp with a trailing newline", ts + "\n"},
		{"decimal timestamp", ts + ".0"},
		{"hex timestamp", "0x" + strconv.FormatInt(now, 16)},
		{"timestamp in milliseconds", strconv.FormatInt(now*1000, 10)},
		{"overflowing timestamp", "99999999999999999999999"},
		{"timestamp in Arabic-Indic digits", "١٧٦٢٩٤١٦٠٠"},
		{"timestamp in full-width digits", "１７６２９４１６００"},
	} {
		vs = append(vs, mk(m.name, vecSecretA, now, m.ts, v1([]byte(vecSecretA), m.ts, body), body, outcomeBadTimestamp))
	}
	return vs
}
